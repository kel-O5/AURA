def get_certification_url(name: str) -> str | None:
    """Official link for a certification name (any casing), or None."""
    entry = CERTIFICATION_CATALOG.get((name or "").strip().lower())
    if not entry or entry["status"] == "retired":
        return None
    url = entry["url"]
    return url if url and url.startswith("https://") else None


def get_certification_status(name: str) -> str | None:
    entry = CERTIFICATION_CATALOG.get((name or "").strip().lower())
    return entry["status"] if entry else None


def missing_catalog_entries() -> list[str]:
    """Certifications used in job_requirements.py that have no catalog entry."""
    from app.data.job_requirements import get_all_known_certifications

    return [c for c in get_all_known_certifications() if c not in CERTIFICATION_CATALOG]


